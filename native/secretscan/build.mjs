// Builds the secret-scan engine to WebAssembly and embeds it in packages/core/src/util/secretscan-wasm.ts.
// Usage: node native/secretscan/build.mjs   (needs: rustup target add wasm32-unknown-unknown)
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../packages/core/src/util/secretscan-wasm.ts");
execFileSync("cargo", ["build", "--release", "--locked", "--target", "wasm32-unknown-unknown"], { cwd: here, stdio: "inherit" });
const wasm = fs.readFileSync(path.join(here, "target/wasm32-unknown-unknown/release/secretscan.wasm"));
const hash = sourceHash();
fs.writeFileSync(out, `/* Generated by native/secretscan/build.mjs from the Rust crate in native/secretscan — do not edit. Rebuild after changing the crate. */
import { setSecretScanEngine } from "./gitleaks";
import { createWasmSecretScan } from "./secretscan";

/** sha256 of the crate sources this module was built from (checked by a test, so a stale build fails CI). */
export const SECRETSCAN_SOURCE_SHA256 = "${hash}";
export const SECRETSCAN_WASM_BYTES = ${wasm.length};
const B64 = "${wasm.toString("base64")}";

export function secretScanWasm(): Uint8Array { const s = atob(B64); const u = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) u[i] = s.charCodeAt(i); return u; }

let installed: boolean | undefined;
/** Use the Rust engine for secret scanning in this process/worker (sync compile: Node, Bun, web workers). Falls back to JS on failure. */
export function installNativeSecretScan(): boolean {
  if (installed !== undefined) return installed;
  try { setSecretScanEngine(createWasmSecretScan(secretScanWasm())); installed = true; } catch { setSecretScanEngine(null); installed = false; }
  return installed;
}
`);
console.log(`wrote ${path.relative(process.cwd(), out)} (${wasm.length} bytes wasm, sources ${hash.slice(0, 12)})`);

/** Exported for the staleness test: hash of Cargo.toml, Cargo.lock and src/**. */
export function sourceHash() {
  const h = createHash("sha256");
  const files = ["Cargo.toml", "Cargo.lock", ...fs.readdirSync(path.join(here, "src")).sort().map((f) => `src/${f}`)];
  for (const f of files) { h.update(f + "\0"); h.update(fs.readFileSync(path.join(here, f))); h.update("\0"); }
  return h.digest("hex");
}
