/**
 * A SCRIPTED stand-in for a language model, used only to test the plumbing end to end
 * (provider adapter → agent tool loop → file writes → acceptance checks → UI). It does not
 * "understand" anything: it writes whatever files the task's `file_exists:` criteria ask for.
 * Never used at runtime; it says so in its model name.
 */
import http from "node:http";

const CORS = { "access-control-allow-origin": "*", "access-control-allow-headers": "*", "access-control-allow-methods": "GET,POST,OPTIONS", "access-control-allow-private-network": "true" };
const sse = (res, chunks) => { res.writeHead(200, { ...CORS, "content-type": "text/event-stream", "cache-control": "no-cache" }); for (const c of chunks) res.write(`data: ${JSON.stringify(c)}\n\n`); res.write("data: [DONE]\n\n"); res.end(); };
const content = (p, objective) => {
  if (p.endsWith(".json")) return JSON.stringify({ name: "mock-app", version: "0.0.1", private: true, scripts: { build: "echo built", test: "node -e \"console.log('tests ok')\"" } }, null, 2) + "\n";
  if (p.endsWith(".html")) return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Mock app</title></head><body><main><h1>Generated by the scripted mock model</h1></main></body></html>\n`;
  if (p.endsWith(".md")) return `# ${p}\n\nWritten by the scripted mock model for: ${objective.split("\n")[0].slice(0, 120)}\n`;
  if (/\.(tsx?|jsx?)$/.test(p)) return `export const generated = true;\n`;
  return `generated\n`;
};

export function createMockLlm({ model = "mock-scripted-coder" } = {}) {
  const calls = [];
  const server = http.createServer((req, res) => {
    if (req.method === "OPTIONS") { res.writeHead(204, CORS); return res.end(); }
    if (req.url.startsWith("/v1/models")) { res.writeHead(200, { ...CORS, "content-type": "application/json" }); return res.end(JSON.stringify({ object: "list", data: [{ id: model, object: "model" }] })); }
    if (req.url.startsWith("/v1/chat/completions") && req.method === "POST") {
      let body = ""; req.on("data", (c) => (body += c)); req.on("end", () => {
        const j = JSON.parse(body); calls.push(j);
        const user = String(j.messages.find((m) => m.role === "user")?.content ?? "");
        const written = j.messages.filter((m) => m.role === "tool" && /^Wrote /.test(String(m.content))).map((m) => String(m.content).split(" ")[1]);
        const wants = [...user.matchAll(/^- file_exists:(.+)$/gm)].map((m) => m[1].trim());
        const next = wants.find((w) => !written.includes(w));
        const tools = j.tools ?? [];
        const call = (name, args, i = 0) => ({ index: i, id: `call_${calls.length}_${i}`, type: "function", function: { name, arguments: JSON.stringify(args) } });
        if (!tools.length) return sse(res, [{ choices: [{ delta: { content: "mock answer" }, index: 0 }] }, { choices: [{ delta: {}, finish_reason: "stop", index: 0 }], usage: { prompt_tokens: 10, completion_tokens: 2 } }]);
        const tc = next ? call("write_file", { path: next, content: content(next, user.split("OBJECTIVE\n")[1] ?? "") }) : call("finish", { summary: `Mock model finished; wrote ${written.length} file(s): ${written.join(", ") || "none"}.` });
        sse(res, [{ choices: [{ delta: { tool_calls: [tc] }, index: 0 }] }, { choices: [{ delta: {}, finish_reason: "tool_calls", index: 0 }], usage: { prompt_tokens: 50, completion_tokens: 20 } }]);
      });
      return;
    }
    res.writeHead(404, CORS); res.end("{}");
  });
  return { server, calls, model, listen: (port = 0) => new Promise((r) => server.listen(port, "127.0.0.1", () => r(`http://127.0.0.1:${server.address().port}`))), close: () => new Promise((r) => server.close(r)) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const m = createMockLlm(); const port = Number(process.env.PORT || 4599);
  m.listen(port).then((u) => console.log(`mock LLM on ${u}/v1 (model ${m.model})`));
}
