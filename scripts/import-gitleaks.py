"""Convert gitleaks' default rules (MIT, github.com/gitleaks/gitleaks/config/gitleaks.toml) into OmniForge rule DATA.
Usage: python3 -I scripts/import-gitleaks.py <gitleaks.toml> <version> > packages/core/src/util/gitleaks-rules.ts
Go RE2 → JS without flags: inline case/dotall modifiers are expanded, (?P<n> → (?<n>, \\z → $, \\A → ^. Rules that still don't compile in JS are
listed in `skipped` (checked by a unit test), never silently dropped."""
import hashlib, json, re, sys, tomllib

src, version = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read(); d = tomllib.loads(raw.decode())

def _class(body, ci):
    """Character-class body; when case-insensitive add the other case of letters and letter ranges."""
    out, i = [], 0
    while i < len(body):
        if body[i] == "\\": out.append(body[i:i + 2]); i += 2; continue
        if i + 2 < len(body) and body[i + 1] == "-" and body[i + 2] != "\\":
            a, b = body[i], body[i + 2]; out.append(body[i:i + 3])
            if ci and a.isalpha() and b.isalpha() and a.isascii() and b.isascii(): out.append((a.swapcase() + "-" + b.swapcase()))
            i += 3; continue
        c = body[i]; out.append(c)
        if ci and c.isascii() and c.isalpha(): out.append(c.swapcase())
        i += 1
    return "".join(out)

def conv(p):
    """RE2 → flag-free JS: inline modifiers ((?i) (?i:…) (?-i:…) (?s:…)) are compiled away so every JS engine accepts it."""
    p = p.replace("(?P<", "(?<").replace("\\z", "$").replace("\\A", "^").replace("[[:alnum:]]", "[A-Za-z0-9]").replace("[:alnum:]", "A-Za-z0-9")
    out, stack, i = [], [[False, False]], 0
    while i < len(p):
        ci, dot = stack[-1]; c = p[i]
        if c == "\\": out.append(p[i:i + 2]); i += 2; continue
        if c == "[":
            j = i + 1; neg = p[j:j + 1] == "^"
            if neg: j += 1
            k = j + (1 if p[j:j + 1] == "]" else 0)
            while p[k] != "]": k += 2 if p[k] == "\\" else 1
            out.append("[" + ("^" if neg else "") + _class(p[j:k], ci) + "]"); i = k + 1; continue
        m = re.match(r"\(\?([a-z]*)(?:-([a-z]*))?([:)])", p[i:]) if c == "(" else None
        if m and (m.group(1) or m.group(2) is not None):
            on, off = m.group(1), m.group(2) or ""
            mode = [(ci or "i" in on) and "i" not in off, (dot or "s" in on) and "s" not in off]
            if m.group(3) == ")": stack[-1] = mode
            else: stack.append(mode); out.append("(?:")
            i += len(m.group(0)); continue
        if c == "(":
            m2 = re.match(r"\(\?(?:<[A-Za-z_]\w*>|<=|<!|[:=!])", p[i:])
            pre = m2.group(0) if m2 else "("
            stack.append([ci, dot]); out.append(pre); i += len(pre); continue
        if c == ")": stack.pop() if len(stack) > 1 else None; out.append(")"); i += 1; continue
        if c == "." and dot: out.append("[\\s\\S]"); i += 1; continue
        if ci and c.isascii() and c.isalpha(): out.append("[" + c.lower() + c.upper() + "]"); i += 1; continue
        if c == "{":  # quantifier: copy verbatim
            m3 = re.match(r"\{\d+(?:,\d*)?\}", p[i:])
            if m3: out.append(m3.group(0)); i += len(m3.group(0)); continue
        out.append(c); i += 1
    return ["".join(out), ""]

rules = []
for r in d["rules"]:
    if "regex" not in r: continue
    re_, fl = conv(r["regex"])
    al = []
    for a in r.get("allowlists", []):
        al.append({k: v for k, v in {"regexes": [conv(x) for x in a.get("regexes", [])], "target": a.get("regexTarget", "secret"), "stopwords": a.get("stopwords", []), "paths": [conv(x) for x in a.get("paths", [])], "condition": a.get("condition", "OR")}.items() if v})
    rules.append({k: v for k, v in {"id": r["id"], "re": re_, "flags": fl, "keywords": [k.lower() for k in r.get("keywords", [])], "entropy": r.get("entropy"), "group": r.get("secretGroup"), "path": conv(r["path"]) if "path" in r else None, "allow": al}.items() if v not in (None, [], "")})
g = d.get("allowlist", {})
glob = {"regexes": [conv(x) for x in g.get("regexes", [])], "stopwords": g.get("stopwords", []), "paths": [conv(x) for x in g.get("paths", [])]}
print("/* Generated by scripts/import-gitleaks.py — do not edit by hand. */")
print(f"/* gitleaks {version} default rules, sha256 {hashlib.sha256(raw).hexdigest()}. MIT License, Copyright (c) 2019 Zachary Rice. See THIRD_PARTY_NOTICES.md. */")
print("import type { GitleaksData } from \"./gitleaks\";")
print(f"export const GITLEAKS: GitleaksData = {json.dumps({'version': version, 'rules': rules, 'allow': glob}, separators=(',', ':'))};")
